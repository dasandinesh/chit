const express = require('express');
const mongoose = require('mongoose');
const app = express();
app.use(require('cors')({ origin: (process.env.CLIENT_ORIGIN || 'http://localhost:3000').split(',').map(s => s.trim()), credentials: true }));
app.use(express.json({ limit: '100kb' }));
app.get('/api/health', (req, res) => res.status(mongoose.connection.readyState === 1 ? 200 : 503).json({ database: mongoose.connection.readyState === 1 ? 'connected' : 'disconnected' }));
app.use('/api', (req, res, next) => { res.set('Cache-Control', 'no-store'); next(); });
app.use('/api/auth', require('./auth').router);
app.use('/api', require('./auth').requireAdmin, require('./auth').protectWrites, require('./routes/chitroutes'));
app.use((req, res) => res.status(404).json({ message: 'Route not found' }));
app.use(require('./middleware/error'));
module.exports = app;
