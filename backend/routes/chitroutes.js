const router = require('express').Router();
const c = require('../controller/chitcontroller');
const wrap = handler => (req, res, next) => Promise.resolve(handler(req, res)).catch(next);
router.get('/dashboard', wrap(require('../controller/dashboardcontroller').getDashboard));
router.get('/customer', wrap(c.customers));
router.post('/customeradd', wrap(c.addCustomer));
router.post('/customer/import', wrap(require('../controller/contactImportController').importContacts));
router.get('/customer/:id/balance', wrap(c.customerBalance));
router.post('/customer/:id/pay', wrap(c.customerPay));
router.patch('/customer/:id/opening-balance', wrap(c.openingBalance));
router.get('/chit', wrap(c.chits));
router.post('/chitadd', wrap(c.saveChit));
router.put('/chitadd/:id', wrap(c.saveChit));
router.delete('/chitadd/:id', wrap(c.deleteChit));
router.delete('/chitadd/:id/schedule/:date', wrap(c.skipScheduledInstallment));
router.get('/chitdue', wrap(c.dues));
router.get('/chitdue/:id', wrap(c.getDue));
router.put('/chitdue/:id', wrap(c.editDue));
router.delete('/chitdue/:id', wrap(c.deleteDue));
router.delete('/chitdue/:id/permanent', wrap(c.permanentlyDeleteDue));
router.post('/chitdue/:id/restore', wrap(c.restoreDue));
router.post('/chitdueadd', wrap(c.addDue));
router.get('/dueamountunwind', wrap(c.flatDues));
router.post('/chitdueamountupdate', wrap(c.pay));
router.get('/getaccount', wrap(c.accounts));
router.post('/postcredit', wrap(c.addAccount));
module.exports = router;
